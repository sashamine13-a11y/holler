const translations: Record<Locale, Record<string, string>> = { en, ru, es, de };

const STORAGE_KEY = 'holler_locale';

export function detectLocale(): Locale {
  if (typeof window === 'undefined') return 'en';
  try {
    const stored = localStorage.getItem(STORAGE_KEY) as Locale | null;
    if (stored && translations[stored]) return stored;
    const browser = navigator.language?.slice(0, 2) as Locale | undefined;
    if (browser && translations[browser]) return browser;
  } catch { /* SSR / private mode */ }
  return 'en';
}

export interface I18nContextValue {
  locale: Locale;
  /** Translate a key, falling back to English and then to the key itself. */
  t: (key: string) => string;
  /** Switch language globally (persisted in localStorage). */
  setLocale: (l: Locale) => void;
  /** BCP-47 tag to use for toLocaleDateString etc. */
  dateLocale: string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

/** App-level provider — mount once in layout.tsx so every component shares one locale. */
export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('en');

  useEffect(() => {
    setLocaleState(detectLocale());
  }, []);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try { localStorage.setItem(STORAGE_KEY, l); } catch { /* ignore */ }
  }, []);

  const t = useCallback((key: string): string => {
    return translations[locale]?.[key] || translations.en[key] || key;
  }, [locale]);

  const dateLocale = locale === 'ru' ? 'ru-RU'
    : locale === 'de' ? 'de-DE'
    : locale === 'es' ? 'es-ES'
    : 'en-GB';

  const value = useMemo<I18nContextValue>(
    () => ({ locale, t, setLocale, dateLocale }),
    [locale, t, setLocale, dateLocale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within <I18nProvider>');
  return ctx;
}

